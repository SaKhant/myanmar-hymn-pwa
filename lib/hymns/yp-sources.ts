export function ypSource(ypNumber:number|string|null|undefined):YpSource|undefined {
  if(ypNumber==null)return undefined;
  const parsed=Number(ypNumber);
  if(!Number.isInteger(parsed))return undefined;
  return VERIFIED_YP_SOURCES[parsed];
}

export function ypSourceLabel(ypNumber:number|string|null|undefined):string|undefined {
  const source=ypSource(ypNumber);
  if(!source)return undefined;
  if(source.collection==="hymn")return `HYM${source.number}`;
  if(source.collection==="c")return `C${source.number}`;
  return `${source.collection.toUpperCase()}${source.number}`;
}

export function ypAudioUrl(ypNumber:number|string|null|undefined):string|undefined {
  const source=ypSource(ypNumber);
  if(!source)return undefined;
  if(source.collection==="ns")return `https://www.hymnal.net/Hymns/NewSongs/mp3/ns${String(source.number).padStart(4,"0")}.mp3`;
  if(source.collection==="lb")return `https://www.hymnal.net/Hymns/LongBeach/mp3/lb${source.number}.mp3`;
  if(source.collection==="c")return `https://www.hymnal.net/Hymns/Children/mp3/c${String(source.number).padStart(4,"0")}.mp3`;
  return `https://www.hymnal.net/Hymns/Hymnal/mp3/e${String(source.number).padStart(4,"0")}_i.mp3`;
}
